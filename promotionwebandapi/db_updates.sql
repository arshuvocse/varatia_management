CREATE TABLE SavedPosts (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    UserId NVARCHAR(255) NOT NULL,
    PostId INT NOT NULL,
    PostType NVARCHAR(50) NOT NULL,
    SavedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);

CREATE TABLE TenantChatConversations (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    TenantUserId NVARCHAR(255) NOT NULL,
    OwnerUserId NVARCHAR(255) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    LastMessageAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);

CREATE TABLE TenantChatMessages (
    Id BIGINT IDENTITY(1,1) PRIMARY KEY,
    ConversationId INT NOT NULL FOREIGN KEY REFERENCES TenantChatConversations(Id),
    SenderUserId NVARCHAR(255) NOT NULL,
    MessageText NVARCHAR(MAX) NOT NULL,
    SentAt DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    ReadAt DATETIME2 NULL
);
